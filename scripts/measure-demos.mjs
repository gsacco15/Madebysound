// Renders each demo song in Chromium, runs it through js/analysis.js and writes the features to
// js/demo-features.js. Run it after changing a demo, with the app served on port 5173 (`npm start`):
//   node scripts/measure-demos.mjs
import { writeFileSync } from 'node:fs';
import { chromium } from 'playwright';

const url = process.env.APP_URL || 'http://127.0.0.1:5173/';
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(url);
const results = await page.evaluate(async () => {
  const { DEMOS, renderDemo } = await import('./js/demos.js');
  const { analyzeAudioBuffer } = await import('./js/analysis.js');
  const out = {};
  for (const demo of DEMOS) out[demo.id] = await analyzeAudioBuffer(await renderDemo(demo));
  return out;
});
await browser.close();

const lines = Object.entries(results).map(([id, f]) => `  '${id}': ${JSON.stringify(f)},`);
const source = `// Generated by scripts/measure-demos.mjs from the rendered demo audio. Do not edit by hand.
// Baked in so demo notes appear instantly and look the same in every browser.
export const DEMO_FEATURES = {
${lines.join('\n')}
};
`;
writeFileSync(new URL('../js/demo-features.js', import.meta.url), source);
for (const [id, f] of Object.entries(results)) console.log(id, f.key, `${f.tempo} BPM`);
